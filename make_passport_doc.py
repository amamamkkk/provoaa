# -*- coding: utf-8 -*-
from docx import Document
from docx.shared import Pt, Cm
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml.ns import qn

doc = Document()
normal = doc.styles["Normal"]
normal.font.name = "Times New Roman"
normal.font.size = Pt(12)
normal._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
for section in doc.sections:
    section.top_margin = Cm(1.5)
    section.bottom_margin = Cm(1.5)
    section.left_margin = Cm(1.7)
    section.right_margin = Cm(1.2)


def h(text, size=18):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(text)
    r.bold = True
    r.font.size = Pt(size)


def sub(text):
    p = doc.add_paragraph()
    r = p.add_run(text)
    r.bold = True
    r.font.size = Pt(13)


def q(text):
    p = doc.add_paragraph()
    r = p.add_run(text)
    r.bold = True
    r.font.size = Pt(11)


def ans(text, italic=False):
    p = doc.add_paragraph()
    r = p.add_run(text)
    if italic:
        r.italic = True
    r.font.size = Pt(11)


# ================= ЗАГОЛОВОК =================
h("ПАСПОРТ ПРОЕКТА")
p = doc.add_paragraph()
p.alignment = WD_ALIGN_PARAGRAPH.CENTER
r = p.add_run("Город будущего · акселератор проектов")
r.font.size = Pt(12)

fields = [
    ("Название команды", "Один в поле"),
    ("Участники (1–4)", "1"),
    ("Сектор города", "Безопасность"),
    ("Дата фиксации", "08.08.2026"),
]
tbl = doc.add_table(rows=len(fields), cols=2)
tbl.style = "Table Grid"
for i, (k, v) in enumerate(fields):
    tbl.cell(i, 0).text = k
    tbl.cell(i, 1).text = v

p = doc.add_paragraph()
r = p.add_run("Подпись преподавателя: ______________________")
r.font.size = Pt(12)
p = doc.add_paragraph()
r = p.add_run("После подписи тема не меняется. Улучшать можно, менять — нет.")
r.font.size = Pt(10)
r.italic = True

# ================= ЧАСТЬ 1 =================
h("ЧАСТЬ 1. Идея")

q("Тема: «Тревожная точка»")

q("1. Проблема сегодня")
ans("Об опасных местах в городе знают только местные жители. Новый человек — приезжий, "
    "студент, турист, новый житель района — узнаёт о таких местах, только когда уже "
    "туда попал. Открытого источника, где можно заранее проверить «а безопасен ли этот "
    "двор?», в городе нет.")

q("2. Кто от этого страдает")
ans("1. Новый житель / приезжий — не знает местных рисков и случайно попадает в опасные места.")
ans("2. Турист — гуляет по городу, не подозревая, какие районы криминальные.")
ans("3. Местные жители — знают об опасности, но не могут донести это до незнакомца, "
    "у них нет инструмента для этого.")

q("3. Скачок в будущее")
ans("В городе будущего у каждого человека есть открытая карта тревожных точек: где было "
    "опасно, какой тип опасности, в какое время суток, сколько подтверждений собрано "
    "и устранено ли уже. Новый человек планирует маршрут, а не натыкается на опасность.")
ans("Значит, кто-то хранит данные: городской сервис безопасности хранит сами точки, "
    "типы опасности, время суток, подтверждения жителей и статус «устранено».")

q("4. Главная история")
ans("Как новый житель города, я хочу заранее видеть опасные места на карте с типом "
    "опасности и временем суток, чтобы обходить их и не попадать в неприятности.")

q("5. Название системы")
ans("«Тревожная точка» — карта опасных мест города с подтверждениями жителей.")

q("6. Чем измерим, что стало лучше")
ans("Снижение числа людей, попавших в опасные места; время появления новой точки на карте "
    "после первого сообщения; доля точек с подтверждением от двух и более жителей; "
    "актуальность статусов «устранено» (точки не висят вечно).")

# ================= ЧАСТЬ 2 =================
h("ЧАСТЬ 2. Паспорт данных")

tbl = doc.add_table(rows=1, cols=4)
tbl.style = "Table Grid"
hdr = tbl.rows[0].cells
for j, t in enumerate(["№", "Что храним", "Структура", "Почему именно она"]):
    hdr[j].text = t

rows = [
    ("1", "Тревожная точка",
     "dict: id точки → все данные о ней",
     "Нужно мгновенно находить точку по её номеру и дополнять её (подтверждения, "
     "статус). Поиск по ключу — быстрый, порядок точек не важен."),
    ("2", "Координаты точки",
     "tuple (широта, долгота)",
     "Пара значений, которая не меняется и не редактируется отдельно — ровно тот "
     "случай, для которого существует tuple."),
    ("3", "Тип опасности + время суток",
     "list из tuple (тип, время_суток)",
     "В одной точке может быть несколько опасностей с разным временем: «кражи — "
     "вечером», «тёмный проход — ночью». Порядок важен, дубликаты допустимы."),
    ("4", "Подтверждения от жителей",
     "set: id жителей, подтвердивших точку",
     "Важен только факт «житель подтвердил», дубликаты недопустимы (один человек — "
     "один голос), порядок не нужен. Set решает это из коробки."),
    ("5", "Статус точки",
     "строка из набора: 'новая', 'подтверждена', 'устранено'",
     "Короткий список возможных значений, строка читается человеком и хранится "
     "как атрибут точки в её dict."),
]
for row in rows:
    cells = tbl.add_row().cells
    for j, val in enumerate(row):
        cells[j].text = val

p = doc.add_paragraph()
r = p.add_run("Подсказка: какую структуру когда берут")
r.bold = True
r.font.size = Pt(10)

tip = doc.add_table(rows=5, cols=2)
tip.style = "Table Grid"
tips = [
    ("list", "важен порядок, дубликаты допустимы, элементы перебираем по очереди"),
    ("dict", "есть ключ, по которому ищем мгновенно: номер → объект, имя → счётчик"),
    ("set", "важен только факт наличия, дубликаты недопустимы, порядок не нужен"),
    ("tuple", "пара или тройка значений, которая не меняется: координаты, дата"),
]
for i, (k, v) in enumerate(tips):
    tip.cell(i, 0).text = k
    tip.cell(i, 1).text = v

sub("Контрольные вопросы к себе")
q("1. Есть ли набор данных, в котором ищем элемент? Точно ли это не list?")
ans("Да — база точек (dict). Ищем точку по её id, чтобы дополнить подтверждения или "
    "поменять статус. Именно dict, потому что важно искать мгновенно по ключу, а "
    "порядок точек не важен.")
q("2. Какой набор данных вырастет больше всех за год работы системы?")
ans("Подтверждения от жителей — с каждым сообщением о точке добавляются голоса. "
    "Также растёт число самих точек по мере того, как о них узнаёт всё больше людей.")
q("3. С каким соседним сектором обмениваемся данными: что берём, что отдаём?")
ans("Сектор безопасности (полиция/охрана): отдаём подтверждённые точки с типом и "
    "временем, получаем обратно статус «устранено». Сектор картографии/навигации: "
    "отдаём точки для отображения, берём карту города.")

# ================= ЧАСТЬ 3 =================
h("ЧАСТЬ 3. Что из этого идёт на защиту")

p = doc.add_paragraph()
r = p.add_run("Защита перед комиссией акселератора. Они не знают про карту города, "
              "сектора и стикеры — это внутренняя кухня. На презентацию попадает "
              "содержимое паспорта:")
r.font.size = Pt(11)

tbl = doc.add_table(rows=7, cols=2)
tbl.style = "Table Grid"
pres = [
    ("Поле паспорта", "Куда идёт в презентации"),
    ("Проблема сегодня", "Слайд 1. Одна фраза, понятная любому взрослому"),
    ("Кто страдает", "Слайд 2. Пользователи и почему им важно"),
    ("Скачок в будущее", "Слайд 3. Как должно быть, тема «город будущего»"),
    ("Главная история", "Слайд 4. Что делает система — одним предложением"),
    ("Название", "Титульный слайд"),
    ("Чем измерим", "Последний слайд — комиссия чаще всего спрашивает именно это"),
]
for i, row in enumerate(pres):
    for j, val in enumerate(row):
        tbl.cell(i, j).text = val

p = doc.add_paragraph()
r = p.add_run("Паспорт данных (часть 2) — слайд про устройство системы, показывает инженерную "
              "составляющую. Карта города, секторы, голоса — НЕ идёт в презентацию.")
r.font.size = Pt(11)

sub("Проверка на постороннего")
ans("Прочитай первую часть паспорта человеку, который не был на занятии. Если понял "
    "проблему и решение без уточняющих вопросов — проект готов к защите.")

